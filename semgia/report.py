"""Course report helpers: one row per sample for data/metadata.csv and for QUALITY-REPORT.md.

Used by scripts/export_metadata.py, scripts/check_quality.py and scripts/train.py (skips rejected samples).
"""

from pathlib import Path

import numpy as np
import pandas as pd

from semgia import config
from semgia.recorder import SAMPLE_N
from semgia.storage import METADATA_FIELDS, list_samples, load_sample

# Required columns of data/metadata.csv (docs/course/requirements.md), then file_name, then our own fields.
COURSE_COLUMNS = ["session", "date", "rest_s", "warning_s", "move_s", "between_s", "electrode_type",
                  "electrode_distance_cm", "skin_preparation", "sensor_model", "gain", "fs_hz", "adc_bits",
                  "set"]
# Our metadata.json fields, minus the ones already in COURSE_COLUMNS (electrode_type) -> no duplicate column.
OWN_COLUMNS = [f for f in METADATA_FIELDS if f not in COURSE_COLUMNS]
QUALITY_COLUMNS = ["sample", "session", "rows", "verdict", "reason"]


def split_of(placement_id: str) -> str:
    """'test' if the placement is in config.TEST_PLACEMENTS, else 'train'."""
    return "test" if placement_id in config.TEST_PLACEMENTS else "train"


def metadata_row(meta: dict, file_name: str) -> dict:
    """One row of data/metadata.csv. Timing comes from config.SAMPLE_STEPS (rest / contract / rest)."""
    (_, rest_s), (_, move_s), (_, between_s) = config.SAMPLE_STEPS
    row = {
        "session": meta.get("placement_id", ""),
        "date": str(meta.get("start_time_utc", ""))[:10],   # "2026-11-20T10:00:00+00:00" -> "2026-11-20"
        "rest_s": rest_s,
        "warning_s": config.WARNING_S,
        "move_s": move_s,
        "between_s": between_s,
        "electrode_type": meta.get("electrode_type", ""),
        "electrode_distance_cm": config.ELECTRODE_DISTANCE_CM,
        "skin_preparation": config.SKIN_PREPARATION,
        "sensor_model": config.SENSOR_MODEL,
        "gain": config.GAIN,
        "fs_hz": meta.get("sampling_rate_hz", config.FS),
        "adc_bits": config.ADC_BITS,
        "set": split_of(meta.get("placement_id", "")),
        "file_name": file_name,
    }
    row.update({k: meta.get(k, "") for k in OWN_COLUMNS})
    return row


def check_signal(df: pd.DataFrame) -> str:
    """Quality rule. Returns "" if the sample is ok, else the reason it is rejected."""
    reasons = []
    if df[["t_s", "value", "label"]].isna().any().any():
        reasons.append("missing value (NaN)")
    adc_max = 2 ** config.ADC_BITS - 1
    n_limit = int(((df.value == 0) | (df.value == adc_max)).sum())
    if n_limit:
        reasons.append(f"{n_limit} values at ADC limit (0 or {adc_max})")
    gaps = int((np.diff(df.t_s.to_numpy()) > config.GAP_TOLERANCE_S).sum())
    if gaps:
        reasons.append(f"{gaps} gaps in t_s (missing rows)")
    if abs(len(df) - SAMPLE_N) > config.MAX_LENGTH_DEVIATION * SAMPLE_N:
        reasons.append(f"length {len(df)} rows, expected {SAMPLE_N} +- {config.MAX_LENGTH_DEVIATION:.0%}")
    return "; ".join(reasons)


def check_subject(meta: dict) -> str:
    """One person only (course rule): "" if the sample is from config.PATIENT_ID, else the reason."""
    subject = meta.get("subject_id", "")
    if subject == config.PATIENT_ID:
        return ""
    return f"other subject {subject} (project = one person, {config.PATIENT_ID})"


def reject_reason(df: pd.DataFrame, meta: dict) -> str:
    """The full rejection rule (signal + subject): "" if ok. Used by QUALITY-REPORT, train and evaluate."""
    return "; ".join(r for r in (check_signal(df), check_subject(meta)) if r)


def quality_row(df: pd.DataFrame, meta: dict) -> dict:
    """One row of QUALITY-REPORT.md."""
    reason = reject_reason(df, meta)
    return {"sample": meta.get("sample_id", ""), "session": meta.get("placement_id", ""), "rows": len(df),
            "verdict": "rejected" if reason else "ok", "reason": reason}


def metadata_table(data: Path, repo_root: Path = config.ROOT) -> pd.DataFrame:
    """data/metadata.csv content for every sample in `data`. file_name is relative to the repo if possible."""
    rows = []
    for d in list_samples(data):
        _, meta = load_sample(d)
        f = (d / "signal.csv").resolve()
        name = f.relative_to(repo_root).as_posix() if f.is_relative_to(repo_root) else f.as_posix()
        rows.append(metadata_row(meta, name))
    return pd.DataFrame(rows, columns=COURSE_COLUMNS + ["file_name"] + OWN_COLUMNS)


def quality_table(data: Path) -> pd.DataFrame:
    """Quality verdict for every sample in `data`."""
    rows = [quality_row(*load_sample(d)) for d in list_samples(data)]
    return pd.DataFrame(rows, columns=QUALITY_COLUMNS)


def quality_markdown(table: pd.DataFrame) -> str:
    """QUALITY-REPORT.md: the rule first (fixed before any score), then one row per sample."""
    adc_max = 2 ** config.ADC_BITS - 1
    n_bad = int((table.verdict == "rejected").sum())
    lines = [
        "# Quality report",
        "",
        "Generated by `python scripts/check_quality.py`. Do not edit by hand.",
        "",
        "## Rejection rule (fixed before any model score)",
        "A recording is rejected if any of these is true:",
        f"- a value sits at the ADC limit: 0 or {adc_max} ({config.ADC_BITS}-bit ADC) -> clipped signal",
        "- a value is missing (NaN) or a row is missing (gap in `t_s` larger than one sample)",
        f"- it is not from the patient {config.PATIENT_ID} (one person, one muscle)",
        f"- its length is off by more than {config.MAX_LENGTH_DEVIATION:.0%} from {SAMPLE_N} rows "
        f"({SAMPLE_N // config.FS} s at {config.FS} Hz)",
        "",
        "Rejected recordings stay in `data/raw/` untouched; "
        "`scripts/train.py` and `scripts/evaluate.py` skip them.",
        "",
        f"## Result: {len(table)} recordings, {len(table) - n_bad} ok, {n_bad} rejected",
        "",
        "| " + " | ".join(QUALITY_COLUMNS) + " |",
        "|" + "---|" * len(QUALITY_COLUMNS),
    ]
    for r in table.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in r) + " |")
    return "\n".join(lines) + "\n"
